/**
 * Code block in the shadcn pattern: CodeBlock (frame), CodeBlockGroup (header row) and CodeBlockCode (body).
 * Code stays on a dark surface even though the panel is light. Colours come from the panel's scoped
 * variables (--vos-dk-* in index.css), not from global tokens.
 * Highlighting is loaded on first use (see src/lib/highlight.ts); plain text shows until it is ready.
 */
import { useEffect, useRef, useState, type ReactNode } from "react";
import { Check, Copy } from "lucide-react";
import { cn } from "@/lib/utils";
import { copyToClipboard } from "@/lib/clipboard";
import { highlight, type CodeLang } from "@/lib/highlight";

export function CodeBlock({ className, children }: { className?: string; children: ReactNode }) {
  return (
    <div className={cn("vos-dark overflow-hidden rounded-lg border border-(--vos-dk-line) bg-(--vos-dk-bg) text-(--vos-dk-text)", className)}>
      {children}
    </div>
  );
}

function CopyCodeButton({ code }: { code: string }) {
  const [copied, setCopied] = useState(false);
  const timer = useRef(0);
  useEffect(() => () => window.clearTimeout(timer.current), []);
  return (
    <button
      type="button"
      onClick={async () => {
        if (!(await copyToClipboard(code))) return;
        setCopied(true);
        window.clearTimeout(timer.current);
        timer.current = window.setTimeout(() => setCopied(false), 2000);
      }}
      className="inline-flex items-center gap-1.5 rounded-md border border-(--vos-dk-line) px-2 py-1 text-[12px] text-(--vos-dk-soft) transition-colors hover:border-white/30 hover:text-white"
    >
      {copied ? <Check className="size-3.5 text-(--vos-dk-green)" aria-hidden /> : <Copy className="size-3.5" aria-hidden />}
      <span>{copied ? "Copied" : "Copy"}</span>
      <span className="sr-only" aria-live="polite">{copied ? "Code copied to clipboard" : ""}</span>
    </button>
  );
}

/** Header row: language chip, file name, optional extras, copy button. */
export function CodeBlockGroup({
  language,
  filename,
  code,
  className,
  children,
}: {
  language: string;
  filename?: string;
  /** The text the copy button copies. */
  code: string;
  className?: string;
  children?: ReactNode;
}) {
  return (
    <div className={cn("flex items-center gap-2 border-b border-(--vos-dk-line) bg-(--vos-dk-head) px-3 py-1.5", className)}>
      <span className="rounded bg-white/[0.1] px-1.5 py-0.5 font-mono text-[11px] text-(--vos-dk-soft)">{language}</span>
      {filename && <span className="min-w-0 flex-1 truncate font-mono text-[12px] text-(--vos-dk-muted)">{filename}</span>}
      {!filename && <span className="flex-1" />}
      {children}
      <CopyCodeButton code={code} />
    </div>
  );
}

/**
 * Code body. `plain` keeps plain text on screen (use it while text is still being typed, so highlighting
 * does not run on every character). Without `plain`, the highlighted version replaces the plain one when ready.
 */
export function CodeBlockCode({
  code,
  language,
  className,
  plain = false,
}: {
  code: string;
  language: CodeLang;
  className?: string;
  plain?: boolean;
}) {
  const [done, setDone] = useState<{ code: string; language: CodeLang; html: string } | null>(null);

  useEffect(() => {
    if (plain) return;
    let live = true;
    highlight(code, language)
      .then((html) => { if (live) setDone({ code, language, html }); })
      .catch(() => { /* stay on plain text */ });
    return () => { live = false; };
  }, [code, language, plain]);

  if (!plain && done && done.code === code && done.language === language) {
    // the HTML is generated by shiki from our own strings, which it escapes
    return <div className={cn("vos-shiki", className)} dangerouslySetInnerHTML={{ __html: done.html }} />;
  }
  return (
    <pre tabIndex={0} className={cn("m-0 overflow-x-auto p-3 font-mono text-[12px] leading-relaxed text-(--vos-dk-text)", className)}>
      <code>{code}</code>
    </pre>
  );
}
